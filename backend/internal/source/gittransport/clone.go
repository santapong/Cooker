// CloneOptions contains only approved connection data, never a clone URL from
// an event. GitBin is a trusted operator/test dependency, not a request field.
type CloneOptions struct {
	Config      Config
	Credentials Credentials
	Repository  string
	Commit      string
	LogWriter   io.Writer
	GitBin      string
}
type setting struct{ key, value string }

func isolatedEnvironment(home string, extra []setting) []string {
	settings := []setting{
		{"core.hooksPath", "/dev/null"}, {"credential.helper", ""}, {"credential.interactive", "false"},
		{"protocol.allow", "never"}, {"protocol.https.allow", "always"}, {"http.followRedirects", "false"},
		{"http.sslVerify", "true"}, {"http.proxy", ""}, {"http.extraHeader", ""},
		{"http.lowSpeedLimit", "1"}, {"http.lowSpeedTime", "30"}, {"http.maxRequests", "2"},
		{"core.fsmonitor", "false"}, {"core.attributesFile", "/dev/null"},
		{"submodule.recurse", "false"}, {"fetch.recurseSubmodules", "false"}, {"fetch.fsckObjects", "true"},
		{"filter.lfs.process", ""}, {"filter.lfs.smudge", ""}, {"filter.lfs.required", "false"},
	}
	settings = append(settings, extra...)
	env := []string{"PATH=/usr/bin:/bin", "LANG=C", "LC_ALL=C", "HOME=" + home, "XDG_CONFIG_HOME=" + home, "GIT_CONFIG_NOSYSTEM=1", "GIT_CONFIG_GLOBAL=/dev/null", "GIT_TERMINAL_PROMPT=0", "GIT_ASKPASS=/bin/false", "SSH_ASKPASS=/bin/false", "GIT_LFS_SKIP_SMUDGE=1", "GIT_NO_REPLACE_OBJECTS=1", "GIT_CONFIG_COUNT=" + strconv.Itoa(len(settings))}
	for i, s := range settings {
		env = append(env, fmt.Sprintf("GIT_CONFIG_KEY_%d=%s", i, s.key), fmt.Sprintf("GIT_CONFIG_VALUE_%d=%s", i, s.value))
	}
	return env
}

type boundedOutput struct{ buffer bytes.Buffer }

func (b *boundedOutput) Bytes() []byte { return b.buffer.Bytes() }

func (b *boundedOutput) Write(p []byte) (int, error) {
	if b.buffer.Len()+len(p) > 16<<20 {
		return 0, fmt.Errorf("source Git output exceeds limit")
	}
	return b.buffer.Write(p)
}
func gitCommand(ctx context.Context, bin, dir string, env []string, args ...string) ([]byte, error) {
	cmd := exec.CommandContext(ctx, bin, args...)
	cmd.Dir = dir
	cmd.Env = env
	// stderr is deliberately discarded: remote servers can echo the credential.
	// User-facing progress is generated by Cooker, not copied from the server.
	cmd.Stderr = io.Discard
	var out boundedOutput
	cmd.Stdout = &out
	err := cmd.Run()
	if err != nil {
		if ctx.Err() != nil {
			return nil, ctx.Err()
		}
		return nil, fmt.Errorf("source Git operation failed")
	}
	return out.Bytes(), nil
}
func requireGit(ctx context.Context, bin string, env []string) error {
	out, err := gitCommand(ctx, bin, "", env, "--version")
	if err != nil {
		return err
	}
	var major, minor int
	if _, err = fmt.Sscanf(strings.TrimSpace(string(out)), "git version %d.%d", &major, &minor); err != nil || major < 2 || major == 2 && minor < 43 {
		return fmt.Errorf("secure source checkout requires Git 2.43 or newer")
	}
	return nil
}

// CloneExact returns a private directory owned by the caller. Every failure
// removes partial content. The caller must os.RemoveAll(dir) after inspection/build.
func CloneExact(ctx context.Context, opts CloneOptions) (dir string, err error) {
	if err = opts.Config.Validate(); err != nil {
		return "", err
	}
	if err = ValidateRepositoryPath(opts.Repository, true); err != nil {
		return "", err
	}
	if err = ValidateCommit(opts.Commit); err != nil {
		return "", err
	}
	if err = ValidateCredentials(opts.Credentials); err != nil {
		return "", err
	}
	ctx, cancel := context.WithTimeout(ctx, 5*time.Minute)
	defer cancel()
	origin, _ := url.Parse(opts.Config.Origin)
	addresses, err := approvedAddresses(ctx, origin.Hostname(), opts.Config.AllowPrivateNetwork)
	if err != nil {
		return "", err
	}
	port := origin.Port()
	if port == "" {
		port = "443"
	}
	// Pin one validated address in libcurl; Git must not resolve a second time.
	// Failure does not retry with a fresh DNS result or an unvalidated address.
	ip := addresses[0].String()
	if strings.Contains(ip, ":") {
		ip = "[" + ip + "]"
	}
	host := origin.Hostname()
	if strings.Contains(host, ":") {
		host = "[" + host + "]"
	}
	settings := []setting{{"http.curloptResolve", host + ":" + port + ":" + ip}}
	private, err := os.MkdirTemp("", "cooker-git-env-")
	if err != nil {
		return "", err
	}
	defer os.RemoveAll(private)
	if opts.Config.CAPEM != "" {
		ca := filepath.Join(private, "ca.pem")
		if err = os.WriteFile(ca, []byte(opts.Config.CAPEM), 0600); err != nil {
			return "", err
		}
		settings = append(settings, setting{"http." + opts.Config.Origin + "/.sslCAInfo", ca})
	}
	if opts.Credentials.Token != "" {
		header := "Authorization: Basic " + base64.StdEncoding.EncodeToString([]byte(opts.Credentials.Username+":"+opts.Credentials.Token))
		settings = append(settings, setting{"http." + opts.Config.Origin + "/.extraHeader", header})
	}
	env := isolatedEnvironment(private, settings)
	bin := opts.GitBin
	if bin == "" {
		bin = "git"
	}
	if err = requireGit(ctx, bin, env); err != nil {
		return "", err
	}
	dir, err = os.MkdirTemp("", "cooker-source-")
	if err != nil {
		return "", err
	}
	checkoutDir := dir
	defer func() {
		if err != nil {
			os.RemoveAll(checkoutDir)
			dir = ""
		}
	}()
	template := filepath.Join(private, "empty-template")
	if err = os.Mkdir(template, 0700); err != nil {
		return "", err
	}
	if _, err = gitCommand(ctx, bin, dir, env, "init", "--quiet", "--template="+template); err != nil {
		return "", err
	}
	cloneURL := opts.Config.Origin + "/" + opts.Repository + ".git"
	if _, err = gitCommand(ctx, bin, dir, env, "remote", "add", "origin", cloneURL); err != nil {
		return "", err
	}
	if opts.LogWriter != nil {
		_, _ = io.WriteString(opts.LogWriter, "Fetching the accepted source commit.\n")
	}
	if _, err = gitCommand(ctx, bin, dir, env, "fetch", "--quiet", "--depth=1", "--no-tags", "--no-recurse-submodules", "origin", opts.Commit); err != nil {
		return "", err
	}
	var kind []byte
	if kind, err = gitCommand(ctx, bin, dir, env, "cat-file", "-t", opts.Commit); err != nil {
		return "", err
	}
	if strings.TrimSpace(string(kind)) != "commit" {
		return "", fmt.Errorf("accepted source object is not a commit")
	}
	var tree []byte
	if tree, err = gitCommand(ctx, bin, dir, env, "ls-tree", "-r", "-z", opts.Commit); err != nil {
		return "", err
	}
	for _, entry := range strings.Split(string(tree), "\x00") {
		if strings.HasPrefix(entry, "160000 ") {
			return "", fmt.Errorf("source submodules require an explicit supported policy")
		}
	}
	if _, err = gitCommand(ctx, bin, dir, env, "checkout", "--quiet", "--detach", opts.Commit); err != nil {
		return "", err
	}
	// Inspect attributes using Git rather than opening repository-controlled paths
	// (which may be symlinks). A source requiring LFS is not silently incomplete.
	var files []byte
	if files, err = gitCommand(ctx, bin, dir, env, "ls-files", "-z"); err != nil {
		return "", err
	}
	attrs := exec.CommandContext(ctx, bin, "check-attr", "--cached", "-z", "--stdin", "filter")
	attrs.Dir = dir
	attrs.Env = env
	attrs.Stdin = strings.NewReader(string(files))
	attrs.Stderr = io.Discard
	var attrOutput boundedOutput
	attrs.Stdout = &attrOutput
	e := attrs.Run()
	values := attrOutput.Bytes()
	if e != nil {
		return "", fmt.Errorf("cannot inspect source filters")
	}
	fields := strings.Split(string(values), "\x00")
	for i := 2; i < len(fields); i += 3 {
		if fields[i] != "unspecified" && fields[i] != "unset" {
			return "", fmt.Errorf("source content filters, including Git LFS, require an explicit supported policy")
		}
	}
	var head []byte
	if head, err = gitCommand(ctx, bin, dir, env, "rev-parse", "--verify", "HEAD"); err != nil {
		return "", err
	}
	if strings.TrimSpace(string(head)) != opts.Commit {
		return "", fmt.Errorf("checked out source does not match accepted commit")
	}
	if opts.LogWriter != nil {
		_, _ = io.WriteString(opts.LogWriter, "Checked out the accepted source commit.\n")
	}
	return dir, nil
}

// HeadCommit reads only the exact checkout's HEAD with the same isolated env.
func HeadCommit(ctx context.Context, dir string) (string, error) {
	out, err := gitCommand(ctx, "git", dir, isolatedEnvironment("/nonexistent", nil), "rev-parse", "--verify", "HEAD")
	if err != nil {
		return "", err
	}
	sha := strings.TrimSpace(string(out))
	if err := ValidateCommit(sha); err != nil {
		return "", err
	}
	return sha, nil
}

// Environment exposes the same ambient-secret-free settings for compatibility
// callers that have not yet moved to CloneExact. It does not approve a network
// destination; those callers must separately restrict their origin.
func Environment(home string) []string { return isolatedEnvironment(home, nil) }
